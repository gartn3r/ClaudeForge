// Shipped inside a package whose own licence does not cover them: node-pty's copy of
// Windows Terminal's ConPTY, which ClaudeForge hosts every Hosted session in.
function bundledBinaries() {
  const [version] = readdirSync(join(ROOT, 'node_modules', 'node-pty', 'third_party', 'conpty'))
  return [
    {
      name: 'Windows Terminal ConPTY (conpty.dll, OpenConsole.exe, inside node-pty)',
      version,
      license: 'MIT',
      repository: 'https://github.com/microsoft/terminal',
      text: `Copyright (c) Microsoft Corporation. All rights reserved.

MIT License

${MIT_LICENSE}`
    }
  ]
}

function render(packages) {
  const lines = [
    '# Third-party notices',
    '',
    'ClaudeForge is released under the MIT licence (see `LICENSE`). It ships the following third-party software, whose licences are reproduced below.',
    '',
    'The Electron runtime also bundles Chromium and other components; their notices ship with every build as `LICENSES.chromium.html`.',
    '',
    'This file is generated by `npm run notices`; do not edit it by hand.',
    '',
    '| Package | Version | Licence |',
    '| --- | --- | --- |',
    ...packages.map((p) => `| ${p.name} | ${p.version} | ${p.license} |`),
    ''
  ]
  for (const p of packages) {
    lines.push(`## ${p.name} ${p.version}`, '', `Licence: ${p.license}`)
    if (p.repository) lines.push(`Source: ${p.repository.replace(/^git\+/, '')}`)
    lines.push('')
    if (p.text) lines.push('```', p.text.replace(/```/g, "'''"), '```', '')
  }
  return lines.join('\n')
}

const content = render([...productionPackages().map(describe), ...bundledBinaries()]).replace(/\r\n/g, '\n')

if (process.argv.includes('--check')) {
  const current = existsSync(OUTPUT) ? readFileSync(OUTPUT, 'utf8').replace(/\r\n/g, '\n') : ''
  if (current !== content) {
    console.error('THIRD_PARTY_NOTICES.md is out of date. Run `npm run notices` and commit the result.')
    process.exit(1)
  }
  console.log('THIRD_PARTY_NOTICES.md is up to date.')
} else {
  writeFileSync(OUTPUT, content)
  console.log(`Wrote ${OUTPUT}`)
}
