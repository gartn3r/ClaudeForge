// Writes THIRD_PARTY_NOTICES.md from the packages ClaudeForge ships: every
// production dependency (transitively) plus the Electron runtime itself.
// `--check` fails when the committed file is out of date (run in CI).

import { execSync } from 'node:child_process'
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const ROOT = join(import.meta.dirname, '..')
const OUTPUT = join(ROOT, 'THIRD_PARTY_NOTICES.md')
const LICENSE_FILE = /^(licen[cs]e|copying|notice)(\.(md|txt))?$/i
// Shipped inside the app though installed as a development dependency.
const RUNTIME = ['electron']

const manifest = (name) => JSON.parse(readFileSync(join(ROOT, 'node_modules', name, 'package.json'), 'utf8'))

function productionPackages() {
  const tree = JSON.parse(execSync('npm ls --omit=dev --all --json', { cwd: ROOT, encoding: 'utf8' }))
  const names = new Set(RUNTIME)
  // npm ls also lists a package's peer dependencies; only its own dependencies ship with it.
  const walk = (deps = {}, peers = {}) => {
    for (const [name, dep] of Object.entries(deps)) {
      if (name in peers || names.has(name)) continue
      names.add(name)
      walk(dep.dependencies, manifest(name).peerDependencies)
    }
  }
  walk(tree.dependencies)
  return [...names].sort()
}

function describe(name) {
  const dir = join(ROOT, 'node_modules', name)
  const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
  const licenseFile = readdirSync(dir).find((file) => LICENSE_FILE.test(file))
  const text = licenseFile ? readFileSync(join(dir, licenseFile), 'utf8').trim() : undefined
  const repository = typeof pkg.repository === 'string' ? pkg.repository : pkg.repository?.url
  return { name, version: pkg.version, license: pkg.license ?? 'UNKNOWN', repository, text }
}

